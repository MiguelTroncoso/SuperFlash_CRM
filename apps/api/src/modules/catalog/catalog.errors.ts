export type CatalogErrorCode = (typeof CATALOG_ERROR_CODES)[keyof typeof CATALOG_ERROR_CODES];

export function catalogException(
  status: HttpStatus,
  code: CatalogErrorCode,
  message: string,
  details?: Record<string, unknown>,
): HttpException {
  return new HttpException({ statusCode: status, code, message, ...details }, status);
}
