  PRODUCT_NOT_FOUND: 'CATALOG_PRODUCT_NOT_FOUND',
  PRODUCT_SLUG_ALREADY_EXISTS: 'CATALOG_PRODUCT_SLUG_ALREADY_EXISTS',
  PRODUCT_SKU_ALREADY_EXISTS: 'CATALOG_PRODUCT_SKU_ALREADY_EXISTS',
  PRODUCT_INVALID_DEMO: 'CATALOG_PRODUCT_INVALID_DEMO',
  PLAN_NOT_FOUND: 'CATALOG_PLAN_NOT_FOUND',
  PLAN_CODE_ALREADY_EXISTS: 'CATALOG_PLAN_CODE_ALREADY_EXISTS',
